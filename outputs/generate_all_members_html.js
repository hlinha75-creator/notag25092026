function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

function formatSilver(value) {
  return `${new Intl.NumberFormat('pt-BR', { maximumFractionDigits: 0 }).format(Number(value || 0))} prata`;
}

